// ─────────────────── Lịch sử nhu cầu sạc (12 kỳ theo huyện) ───────────────────
function chargingDemandSeries(
  district: string,
  baseKwh: number,
  growthPct: number,
  seasonAmp: number,
): ChargingDemandRecord[] {
  return Array.from({ length: 12 }, (_, i) => {
    const k = i + 1;
    const wave = Math.sin((k - 1) * 0.9) * seasonAmp;
    const energyKwh = Math.round(baseKwh * (1 + (growthPct / 100) * ((k - 1) / 11)) + wave);
    return { district, period: `T${k}`, energyKwh, sessions: Math.round(energyKwh / 22) };
  });
}

